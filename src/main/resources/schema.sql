-- 테이블 정의 (기동할 때마다 실행되므로 IF NOT EXISTS)

CREATE TABLE IF NOT EXISTS CATEGORY (
    ID           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CATEGORYNAME VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS STATION (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LINENAME    VARCHAR(50) NOT NULL,
    STATIONNAME VARCHAR(50) NOT NULL,
    UNIQUE (LINENAME, STATIONNAME)
);

-- 회원
CREATE TABLE IF NOT EXISTS MEMBER (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOGINID          VARCHAR(20) NOT NULL UNIQUE,
    PASSWORD         VARCHAR(100) NOT NULL, -- BCrypt 해시
    REALNAME         VARCHAR(20) NOT NULL,
    NICKNAME         VARCHAR(20) NOT NULL,  -- 게시글 작성자명. 가입 시 비워 두면 REALNAME
    BIRTHDATE        DATE NOT NULL,
    PHONE            VARCHAR(20) NOT NULL,
    AGREEDDATE       TIMESTAMP NOT NULL,    -- 개인정보 취급 동의 일시
    REGISTRATIONDATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 見つけた 게시판 게시글
CREATE TABLE IF NOT EXISTS FOUND_ITEM (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE            VARCHAR(200) NOT NULL,
    FOUNDDATE        DATE NOT NULL,
    LINENAME         VARCHAR(50) NOT NULL,
    STATIONNAME      VARCHAR(50) NOT NULL,
    CATEGORYNAME     VARCHAR(50) NOT NULL,
    ITEMNAME         VARCHAR(100) NOT NULL,
    CONTENTS         VARCHAR(500) NOT NULL,
    IMGPATH          VARCHAR(200),
    PASSWORD         VARCHAR(100),          -- 비회원 글: 4자리 비밀번호의 BCrypt 해시 / 회원 글: NULL
    AUTHOR           VARCHAR(20) NOT NULL,
    REGISTRATIONDATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DEL_FLG          BOOLEAN DEFAULT FALSE NOT NULL,
    MODIFIEDDATE     TIMESTAMP,
    MEMBERID         BIGINT REFERENCES MEMBER(ID) -- 회원 글의 작성자 / 비회원 글: NULL
);

-- 회원 기능 추가 전에 만들어진 DB 대응 (이미 반영돼 있으면 아무 일도 하지 않음)
ALTER TABLE FOUND_ITEM ADD COLUMN IF NOT EXISTS MEMBERID BIGINT REFERENCES MEMBER(ID);
ALTER TABLE FOUND_ITEM ALTER COLUMN PASSWORD SET NULL;

-- 探しています 게시판 게시글 (회원만 작성)
CREATE TABLE IF NOT EXISTS LOST_ITEM (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE            VARCHAR(200) NOT NULL,
    LOSTDATE         DATE NOT NULL,
    LINENAME         VARCHAR(50) NOT NULL,
    STATIONNAME      VARCHAR(50),           -- NULL: 어느 역인지 모름 (駅がわからない)
    CATEGORYNAME     VARCHAR(50) NOT NULL,
    ITEMNAME         VARCHAR(100) NOT NULL,
    CONTENTS         VARCHAR(500) NOT NULL,
    IMGPATH          VARCHAR(200),
    AUTHOR           VARCHAR(20) NOT NULL,  -- 작성 시점의 닉네임
    MEMBERID         BIGINT NOT NULL REFERENCES MEMBER(ID),
    RESOLVED         BOOLEAN DEFAULT FALSE NOT NULL, -- 작성자가 "見つかりました" 로 표시
    REGISTRATIONDATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DEL_FLG          BOOLEAN DEFAULT FALSE NOT NULL,
    MODIFIEDDATE     TIMESTAMP
);
