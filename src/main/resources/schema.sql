-- 테이블 정의 (기동할 때마다 실행되므로 IF NOT EXISTS)

CREATE TABLE IF NOT EXISTS CATEGORY (
    ID           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CATEGORYNAME VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS STATION (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LINENAME    VARCHAR(50) NOT NULL,
    STATIONNAME VARCHAR(50) NOT NULL,
    UNIQUE (LINENAME, STATIONNAME)
);

-- 회원
-- 탈퇴하면 개인정보(ID·비밀번호·氏名·生年月日·電話番号)를 지우고 번호만 남긴다 (글·댓글이 회원 번호로 연결돼 있으므로)
CREATE TABLE IF NOT EXISTS MEMBER (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOGINID          VARCHAR(20) UNIQUE,    -- 탈퇴하면 NULL (같은 ID 로 다시 가입할 수 있음)
    PASSWORD         VARCHAR(100),          -- BCrypt 해시
    REALNAME         VARCHAR(20),
    NICKNAME         VARCHAR(20) NOT NULL,  -- 게시글 작성자명. 가입 시 비워 두면 REALNAME, 탈퇴하면 退会したユーザー
    BIRTHDATE        DATE,
    PHONE            VARCHAR(20),
    AGREEDDATE       TIMESTAMP NOT NULL,    -- 개인정보 취급 동의 일시
    REGISTRATIONDATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    WITHDRAWNDATE    TIMESTAMP              -- 탈퇴 일시 / 탈퇴하지 않은 회원: NULL
);

-- 탈퇴 기능 추가 전에 만들어진 DB 대응 (이미 반영돼 있으면 아무 일도 하지 않음)
ALTER TABLE MEMBER ADD COLUMN IF NOT EXISTS WITHDRAWNDATE TIMESTAMP;
ALTER TABLE MEMBER ALTER COLUMN LOGINID SET NULL;
ALTER TABLE MEMBER ALTER COLUMN PASSWORD SET NULL;
ALTER TABLE MEMBER ALTER COLUMN REALNAME SET NULL;
ALTER TABLE MEMBER ALTER COLUMN BIRTHDATE SET NULL;
ALTER TABLE MEMBER ALTER COLUMN PHONE SET NULL;
-- 탈퇴하지 않은 회원은 개인정보가 모두 있고, 탈퇴한 회원은 모두 비어 있어야 한다
ALTER TABLE MEMBER ADD CONSTRAINT IF NOT EXISTS CK_MEMBER_WITHDRAWN CHECK (
    (WITHDRAWNDATE IS NULL
        AND LOGINID IS NOT NULL AND PASSWORD IS NOT NULL AND REALNAME IS NOT NULL AND BIRTHDATE IS NOT NULL AND PHONE IS NOT NULL)
    OR (WITHDRAWNDATE IS NOT NULL
        AND LOGINID IS NULL AND PASSWORD IS NULL AND REALNAME IS NULL AND BIRTHDATE IS NULL AND PHONE IS NULL)
);
-- ID 는 대소문자를 구분하지 않고 하나만 (가입 화면도 확인하지만, Taro 와 taro 가 동시에 가입하는 경우까지 DB 에서 막는다)
-- 탈퇴한 회원은 LOGINID 가 NULL 이라 여러 명이어도 된다
-- (이미 대소문자만 다른 ID 가 들어 있는 DB 라면 이 문장에서 기동이 멈춘다 → 한쪽 ID 를 바꾼 뒤 다시 기동)
ALTER TABLE MEMBER ADD COLUMN IF NOT EXISTS LOGINKEY VARCHAR(20) GENERATED ALWAYS AS (LOWER(LOGINID));
CREATE UNIQUE INDEX IF NOT EXISTS UK_MEMBER_LOGINKEY ON MEMBER(LOGINKEY);

-- 見つけた 게시판 게시글
CREATE TABLE IF NOT EXISTS FOUND_ITEM (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE            VARCHAR(200) NOT NULL,
    FOUNDDATE        DATE NOT NULL,
    LINENAME         VARCHAR(50) NOT NULL,
    STATIONNAME      VARCHAR(50) NOT NULL,
    CATEGORYNAME     VARCHAR(50) NOT NULL,
    ITEMNAME         VARCHAR(100) NOT NULL,
    CONTENTS         VARCHAR(500) NOT NULL,
    IMGPATH          VARCHAR(200),
    PASSWORD         VARCHAR(100),          -- 비회원 글: 4자리 비밀번호의 BCrypt 해시 / 회원 글: NULL
    AUTHOR           VARCHAR(20) NOT NULL,
    REGISTRATIONDATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DEL_FLG          BOOLEAN DEFAULT FALSE NOT NULL,
    MODIFIEDDATE     TIMESTAMP,
    MEMBERID         BIGINT REFERENCES MEMBER(ID) -- 회원 글의 작성자 / 비회원 글: NULL
);

-- 회원 기능 추가 전에 만들어진 DB 대응 (이미 반영돼 있으면 아무 일도 하지 않음)
ALTER TABLE FOUND_ITEM ADD COLUMN IF NOT EXISTS MEMBERID BIGINT REFERENCES MEMBER(ID);
ALTER TABLE FOUND_ITEM ALTER COLUMN PASSWORD SET NULL;

-- 검색용: 제목+본문을 전각·반각, 대소문자 구분 없이 맞춘 값 (KeywordCondition.searchText. 글을 저장·수정할 때 함께 저장)
-- 이 컬럼이 없던 DB 의 글은 서버를 켤 때 채운다 (SearchTextBackfill)
ALTER TABLE FOUND_ITEM ADD COLUMN IF NOT EXISTS SEARCHTEXT VARCHAR;

-- 探しています 게시판 게시글 (회원만 작성)
CREATE TABLE IF NOT EXISTS LOST_ITEM (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE            VARCHAR(200) NOT NULL,
    LOSTDATE         DATE NOT NULL,
    LINENAME         VARCHAR(50) NOT NULL,
    STATIONNAME      VARCHAR(50),           -- NULL: 어느 역인지 모름 (駅がわからない)
    CATEGORYNAME     VARCHAR(50) NOT NULL,
    ITEMNAME         VARCHAR(100) NOT NULL,
    CONTENTS         VARCHAR(500) NOT NULL,
    IMGPATH          VARCHAR(200),
    AUTHOR           VARCHAR(20) NOT NULL,  -- 작성 시점의 닉네임
    MEMBERID         BIGINT NOT NULL REFERENCES MEMBER(ID),
    RESOLVED         BOOLEAN DEFAULT FALSE NOT NULL, -- 작성자가 "見つかりました" 로 표시
    REGISTRATIONDATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DEL_FLG          BOOLEAN DEFAULT FALSE NOT NULL,
    MODIFIEDDATE     TIMESTAMP
);

-- 검색용 (FOUND_ITEM 과 같음)
ALTER TABLE LOST_ITEM ADD COLUMN IF NOT EXISTS SEARCHTEXT VARCHAR;

-- 목록의 정렬 순서 (작성일·발견일/분실일 + ID). 정렬할 때 모든 글을 읽지 않고 앞에서부터 한 페이지만 읽는다
-- (없으면 글마다 댓글 수를 센 뒤 정렬해서, 글 1만 건에서 목록 한 번에 약 40ms 가 걸렸다)
CREATE INDEX IF NOT EXISTS IX_FOUND_ITEM_REGDATE ON FOUND_ITEM(REGISTRATIONDATE, ID);
CREATE INDEX IF NOT EXISTS IX_FOUND_ITEM_FOUNDDATE ON FOUND_ITEM(FOUNDDATE, ID);
CREATE INDEX IF NOT EXISTS IX_LOST_ITEM_REGDATE ON LOST_ITEM(REGISTRATIONDATE, ID);
CREATE INDEX IF NOT EXISTS IX_LOST_ITEM_LOSTDATE ON LOST_ITEM(LOSTDATE, ID);

-- 댓글 (두 게시판 공통, 회원만 작성)
-- FOUNDITEMID / LOSTITEMID 중 정확히 하나에만 값이 들어간다
CREATE TABLE IF NOT EXISTS POST_COMMENT (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FOUNDITEMID      BIGINT REFERENCES FOUND_ITEM(ID),
    LOSTITEMID       BIGINT REFERENCES LOST_ITEM(ID),
    CONTENTS         VARCHAR(500) NOT NULL,
    AUTHOR           VARCHAR(20) NOT NULL,  -- 작성 시점의 닉네임
    MEMBERID         BIGINT NOT NULL REFERENCES MEMBER(ID),
    REGISTRATIONDATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DEL_FLG          BOOLEAN DEFAULT FALSE NOT NULL,
    CHECK ((FOUNDITEMID IS NULL) <> (LOSTITEMID IS NULL))
);

-- 역 위치 (駅マップ). 같은 역이 여러 노선에 있어도 위치는 하나
CREATE TABLE IF NOT EXISTS STATION_LOCATION (
    STATIONNAME VARCHAR(50) PRIMARY KEY,
    LATITUDE    DECIMAL(9, 6) NOT NULL,
    LONGITUDE   DECIMAL(9, 6) NOT NULL
);
